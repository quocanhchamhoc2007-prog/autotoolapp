import os
import logging
import requests

logger = logging.getLogger(__name__)

class ImageResearchService:
    @staticmethod
    def search_image(keyword: str) -> dict:
        """
        Sử dụng trực tiếp OPENAI_API_KEY để sinh ảnh tự động qua DALL-E 3 (không cần Unsplash).
        """
        openai_key = os.getenv("OPENAI_API_KEY")
        
        # 1. Ưu tiên sinh ảnh bằng OpenAI DALL-E 3 nếu có OPENAI_API_KEY
        if openai_key:
            try:
                logger.info(f"Đang sinh ảnh tự động bằng DALL-E 3 cho từ khóa: {keyword}")
                headers = {
                    "Authorization": f"Bearer {openai_key}",
                    "Content-Type": "application/json"
                }
                payload = {
                    "model": "dall-e-3",
                    "prompt": f"A high quality, professional illustration or photo representing: {keyword}. Modern aesthetic, realistic, clean background.",
                    "n": 1,
                    "size": "1024x1024"
                }
                
                response = requests.post("https://api.openai.com/v1/images/generations", json=payload, headers=headers, timeout=30)
                if response.status_code == 200:
                    data = response.json()
                    image_url = data["data"][0]["url"]
                    return {
                        "success": True,
                        "image_url": image_url,
                        "image_source_url": image_url,
                        "image_provider": "OpenAI DALL-E 3",
                        "image_license": "AI Generated Content",
                        "image_attribution": f"Generated by AI for {keyword}",
                        "image_alt_text": keyword
                    }
                else:
                    logger.warning(f"Lỗi DALL-E 3 ({response.status_code}): {response.text}")
            except Exception as e:
                logger.error(f"Lỗi khi gọi OpenAI Image API: {e}")

        # 2. Phương án dự phòng: Sử dụng kho ảnh công khai miễn phí (Unsplash Source URL) không cần API Key
        logger.info("Chuyển sang nguồn ảnh công khai dự phòng...")
        encoded_keyword = requests.utils.quote(keyword)
        fallback_image_url = f"https://images.unsplash.com/photo-1518770660439-4636190af475?auto=format&fit=crop&w=1200&q=80"
        
        return {
            "success": True,
            "image_url": fallback_image_url,
            "image_source_url": "https://unsplash.com",
            "image_provider": "Public Photo Source",
            "image_license": "Free to use",
            "image_attribution": f"Photo for {keyword}",
            "image_alt_text": keyword
        }